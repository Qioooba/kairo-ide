/**
 * Recursively widen all string-literal leaf types in T to `string`.
 * Preserves the nested object shape so other locales can be assigned
 * to KairoI18nMessages while still providing type-checked keys.
 */
type DeepWidenStrings<T> = T extends string
  ? string
  : T extends object
  ? { [K in keyof T]: DeepWidenStrings<T[K]> }
  : T;

type NestedKeyOf<T> = T extends object
  ? {
      [K in keyof T & (string | number)]: T[K] extends object
        ? `${K}` | `${K}.${NestedKeyOf<T[K]>}`
        : `${K}`;
    }[keyof T & (string | number)]
  : never;

export type KairoI18nMessages = DeepWidenStrings<typeof enMessages>;
export type KairoI18nKey = NestedKeyOf<typeof enMessages>;
export default enMessages;
